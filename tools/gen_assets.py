#!/usr/bin/env python3
"""Pre-render the digit and vertical-rail bitmaps and their metrics header.

The watch can't rotate text or hold 127 px glyphs in a font resource, so the
big digits and the rotated date rail are drawn from 1-bit palettized PNGs.
Run from the repo root:  python3 tools/gen_assets.py   (needs Pillow)
"""
import math
import os
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = os.path.join(ROOT, "resources", "fonts")
IMAGES = os.path.join(ROOT, "resources", "images")
HEADER = os.path.join(ROOT, "src", "c", "assets.h")

DIGIT_SIZE = 127          # px, matches the 254 px design at 2x
DIGIT_WEIGHT = 900
RAIL_CHARS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789."
RAIL_SIZE = 8             # Silkscreen's native pixel size
RAIL_TRACKING = 1


def save_1bit(mask, path):
    """mask: 'L' image, ink > 127. Saves palette PNG: 0 = clear, 1 = black."""
    out = Image.new("P", mask.size, 0)
    out.putpalette([255, 255, 255, 0, 0, 0])
    out.paste(1, mask=mask.point(lambda v: 255 if v > 127 else 0))
    out.save(path, transparency=0, bits=1, optimize=False)


def gen_digits():
    font = ImageFont.truetype(os.path.join(FONTS, "BigShouldersDisplay.ttf"), DIGIT_SIZE)
    font.set_variation_by_axes([DIGIT_WEIGHT])
    tops, bottoms = [], []
    for c in "0123456789":
        _, t, _, b = font.getbbox(c)
        tops.append(t)
        bottoms.append(b)
    top, bottom = min(tops), max(bottoms)
    height = bottom - top
    advances = []
    for c in "0123456789":
        adv = int(math.ceil(font.getlength(c)))
        img = Image.new("L", (adv, height), 0)
        ImageDraw.Draw(img).text((0, -top), c, font=font, fill=255)
        save_1bit(img, os.path.join(IMAGES, f"digit_{c}.png"))
        advances.append(adv)
    return advances, height, top


def gen_rail(font_file, name):
    font = ImageFont.truetype(os.path.join(FONTS, font_file), RAIL_SIZE)
    cap_top, cap_h = 4, 5  # Silkscreen at 8 px: caps occupy rows 4..8
    glyphs, offset, tiles = [], 0, []
    for c in RAIL_CHARS:
        adv = int(round(font.getlength(c))) + RAIL_TRACKING
        img = Image.new("L", (adv, cap_h), 0)
        d = ImageDraw.Draw(img)
        d.fontmode = "1"
        d.text((0, -cap_top), c, font=font, fill=255)
        rot = img.rotate(-90, expand=True)  # clockwise: reads top to bottom
        tiles.append(rot)
        glyphs.append((c, offset, rot.height))
        offset += rot.height
    sheet = Image.new("L", (cap_h, offset), 0)
    y = 0
    for t in tiles:
        sheet.paste(t, (0, y))
        y += t.height
    save_1bit(sheet, os.path.join(IMAGES, f"rail_{name}.png"))
    return glyphs, cap_h


def main():
    os.makedirs(IMAGES, exist_ok=True)
    advances, digit_h, _ = gen_digits()
    bold, rail_w = gen_rail("Silkscreen-Bold.ttf", "bold")
    regular, _ = gen_rail("Silkscreen-Regular.ttf", "regular")
    lines = [
        "// Generated by tools/gen_assets.py; do not edit.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"#define DIGIT_HEIGHT {digit_h}",
        "static const uint8_t DIGIT_ADVANCE[10] = {" + ", ".join(map(str, advances)) + "};",
        "",
        f"#define RAIL_GLYPH_WIDTH {rail_w}",
        f'#define RAIL_CHARS "{RAIL_CHARS}"',
        "typedef struct { uint16_t y; uint8_t h; } RailGlyph;",
    ]
    for name, glyphs in (("BOLD", bold), ("REGULAR", regular)):
        body = ", ".join(f"{{{y}, {h}}}" for _, y, h in glyphs)
        lines.append(f"static const RailGlyph RAIL_{name}[{len(glyphs)}] = {{{body}}};")
    with open(HEADER, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("digits", advances, "height", digit_h)


if __name__ == "__main__":
    main()
